//! Generated app textures: the fallback cover gradient, the real-SVG Rift logo
//! mark (prerasterized PNG) and the old UI's music-note glyph.

use std::sync::atomic::{AtomicBool, Ordering};

use crate::gfx::paint::TextureId;
use crate::ui::Ui;

// ---------------------------------------------------------------------------
// generated textures (gradient tile, logo mark, music-note fallback)
// ---------------------------------------------------------------------------

/// The real `logo.svg`, rasterized at 2x with the CSS drop-shadow baked in
/// (`crates/rift-desktop/assets/logo/logo@2x.png`, regenerated by
/// `python crates/rift-desktop/assets/logo/generate.py`).
static LOGO_PNG: &[u8] = include_bytes!("../../../assets/logo/logo@2x.png");

/// Reserved ids for app-generated textures. Framework textures live below
/// [`crate::ui::FIRST_IMAGE_TEXTURE_ID`] (1024); cover art is allocated upward
/// from 1024, so a high id cannot collide.
pub const COVER_FALLBACK_TEX: TextureId = 1_000_000;
pub const LOGO_TEX: TextureId = 1_000_001;
pub const NOTE_TEX: TextureId = 1_000_002;

/// The logo texture's logical canvas: the 22 px tile plus a 5 px glow margin on
/// every side (`filter: drop-shadow(0 0 3px rgba(157,92,255,.55))` in the CSS).
pub const LOGO_DRAW_SIZE: f32 = 32.0;
pub const LOGO_TILE_INSET: f32 = 5.0;

static TEXTS_UPLOADED: AtomicBool = AtomicBool::new(false);

/// Make sure the app's generated textures exist in the renderer. Called by every
/// cover/logo draw; the upload happens on the first frame only.
pub fn ensure_textures(ui: &mut Ui) {
    if TEXTS_UPLOADED.swap(true, Ordering::Relaxed) {
        return;
    }
    let cover = fallback_cover_rgba(64);
    ui.upload_texture(COVER_FALLBACK_TEX, 64, 64, cover);
    // The titlebar mark is a prerasterized PNG of the real `logo.svg` (2x + the
    // CSS drop-shadow baked in); see `crates/rift-desktop/assets/logo/generate.py`.
    // A corrupt embed must not take the app down: skip the upload and let the
    // titlebar fall back to the text wordmark.
    if let Ok(logo) = image::load_from_memory(LOGO_PNG) {
        let logo = logo.to_rgba8();
        let (w, h) = logo.dimensions();
        ui.upload_texture(LOGO_TEX, w, h, logo.into_raw());
    } else {
        tracing::error!("embedded logo PNG failed to decode; using the text wordmark");
    }
    let (w, h, note) = music_note_rgba(96);
    ui.upload_texture(NOTE_TEX, w, h, note);
}

/// `linear-gradient(135deg, #1c1c22, #141417)` baked into RGBA8.
pub fn fallback_cover_rgba(size: u32) -> Vec<u8> {
    let start = [0x1c, 0x1c, 0x22];
    let end = [0x14, 0x14, 0x17];
    let mut out = Vec::with_capacity((size * size * 4) as usize);
    let denom = (2 * (size - 1)).max(1) as f32;
    for y in 0..size {
        for x in 0..size {
            let t = (x + y) as f32 / denom; // 135deg: top-left -> bottom-right
            for c in 0..3 {
                let v = start[c] as f32 + (end[c] as f32 - start[c] as f32) * t;
                out.push(v.round().clamp(0.0, 255.0) as u8);
            }
            out.push(255);
        }
    }
    out
}

/// The old web UI's `music` icon (a beamed pair of eighth notes), rasterised
/// into a white-glyph RGBA texture so it can be tinted like an atlas glyph.
/// The path is from `ui/src/components/icons.rs`: 24-unit viewBox, filled.
pub fn music_note_rgba(px: usize) -> (u32, u32, Vec<u8>) {
    let contour = music_note_contour();
    let mut out = vec![0u8; px * px * 4];
    const SS: usize = 3;
    for y in 0..px {
        for x in 0..px {
            let mut hits = 0;
            for sy in 0..SS {
                for sx in 0..SS {
                    let lx = (x as f32 + (sx as f32 + 0.5) / SS as f32) / px as f32 * 24.0;
                    let ly = (y as f32 + (sy as f32 + 0.5) / SS as f32) / px as f32 * 24.0;
                    if point_in_polygon(lx, ly, &contour) {
                        hits += 1;
                    }
                }
            }
            let a = (hits as f32 / (SS * SS) as f32 * 255.0).round() as u8;
            let i = (y * px + x) * 4;
            out[i] = 255;
            out[i + 1] = 255;
            out[i + 2] = 255;
            out[i + 3] = a;
        }
    }
    (px as u32, px as u32, out)
}

/// Flattened contour of the old `music` SVG path, in its 24-unit viewBox.
fn music_note_contour() -> Vec<(f32, f32)> {
    let mut pts: Vec<(f32, f32)> = Vec::with_capacity(96);
    pts.push((21.0, 3.0));
    pts.push((21.0, 15.5));
    flatten_cubic(
        &mut pts,
        (21.0, 15.5),
        (21.0, 16.88),
        (19.88, 18.0),
        (18.5, 18.0),
    );
    flatten_cubic(
        &mut pts,
        (18.5, 18.0),
        (17.12, 18.0),
        (16.0, 16.88),
        (16.0, 15.5),
    );
    flatten_cubic(
        &mut pts,
        (16.0, 15.5),
        (16.0, 14.12),
        (17.12, 13.0),
        (18.5, 13.0),
    );
    flatten_cubic(
        &mut pts,
        (18.5, 13.0),
        (18.85, 13.0),
        (19.19, 13.07),
        (19.5, 13.18),
    );
    pts.push((19.5, 8.4));
    pts.push((10.0, 9.7));
    pts.push((10.0, 17.5));
    flatten_cubic(
        &mut pts,
        (10.0, 17.5),
        (10.0, 18.88),
        (8.88, 20.0),
        (7.5, 20.0),
    );
    flatten_cubic(
        &mut pts,
        (7.5, 20.0),
        (6.12, 20.0),
        (5.0, 18.88),
        (5.0, 17.5),
    );
    flatten_cubic(
        &mut pts,
        (5.0, 17.5),
        (5.0, 16.12),
        (6.12, 15.0),
        (7.5, 15.0),
    );
    flatten_cubic(
        &mut pts,
        (7.5, 15.0),
        (7.85, 15.0),
        (8.19, 15.07),
        (8.5, 15.18),
    );
    pts.push((8.5, 6.3));
    pts.push((21.0, 3.0));
    pts
}

/// Append the flattened points of one cubic (excluding the start point).
fn flatten_cubic(
    out: &mut Vec<(f32, f32)>,
    p0: (f32, f32),
    p1: (f32, f32),
    p2: (f32, f32),
    p3: (f32, f32),
) {
    const STEPS: usize = 8;
    for i in 1..=STEPS {
        let t = i as f32 / STEPS as f32;
        let u = 1.0 - t;
        let x =
            u * u * u * p0.0 + 3.0 * u * u * t * p1.0 + 3.0 * u * t * t * p2.0 + t * t * t * p3.0;
        let y =
            u * u * u * p0.1 + 3.0 * u * u * t * p1.1 + 3.0 * u * t * t * p2.1 + t * t * t * p3.1;
        out.push((x, y));
    }
}

/// Even-odd point-in-polygon test (the note outline is a simple contour).
fn point_in_polygon(px: f32, py: f32, contour: &[(f32, f32)]) -> bool {
    let mut inside = false;
    let n = contour.len();
    let mut j = n - 1;
    for i in 0..n {
        let (xi, yi) = contour[i];
        let (xj, yj) = contour[j];
        if ((yi > py) != (yj > py)) && (px < (xj - xi) * (py - yi) / (yj - yi) + xi) {
            inside = !inside;
        }
        j = i;
    }
    inside
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_textures_have_the_right_shape() {
        let cover = fallback_cover_rgba(16);
        assert_eq!(cover.len(), 16 * 16 * 4);
        // Top-left is the gradient start, bottom-right the end.
        assert_eq!(&cover[0..3], &[0x1c, 0x1c, 0x22]);
        let last = cover.len() - 4;
        assert_eq!(&cover[last..last + 3], &[0x14, 0x14, 0x17]);
        assert_eq!(cover[3], 255);

        // The embedded logo is a 64x64 (32 logical px @2x) RGBA PNG from the
        // real SVG: transparent margin, opaque tile in the middle.
        let logo = image::load_from_memory(LOGO_PNG)
            .expect("logo PNG decodes")
            .to_rgba8();
        assert_eq!(logo.dimensions(), (64, 64));
        assert_eq!(logo.get_pixel(0, 0)[3], 0);
        assert_eq!(logo.get_pixel(32, 32)[3], 255);
    }
}
