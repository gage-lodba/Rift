//! Build script: compile the Tauri context (config, icons, capabilities) and
//! declare the app's own command ACL manifest.
//!
//! Declaring an app manifest is what puts Rift's own commands under the ACL.
//! Tauri v2 only enforces the ACL on app-defined commands once the app has a
//! manifest (`tauri::webview::Webview::on_message` checks
//! `runtime_authority.has_app_manifest()`), so without this every command is
//! implicitly reachable from the webview even though
//! `capabilities/default.json` looks like it is scoping things. With it, the
//! granted set is explicit, and `tauri-build` fails the build if a capability
//! names a permission that does not exist — so a renamed command breaks CI
//! rather than silently widening access.
//!
//! The autogenerated per-command permissions are summarised by
//! `permissions/default.toml`, which is what `capabilities/default.json` grants.
//! Every command registered in `src/main.rs`'s `invoke_handler` must be listed
//! here, or the webview's call to it is rejected at runtime.

fn main() {
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            // Metadata / browsing
            "search",
            "search_artists",
            "search_albums",
            "get_artist",
            "get_artist_songs",
            "get_album",
            // Transport and playback state
            "play_tracks",
            "play_track",
            "toggle_play",
            "next_track",
            "prev_track",
            "seek",
            "set_volume",
            "save_volume",
            "set_discord_rpc",
            "set_crossfade",
            "toggle_shuffle",
            "cycle_repeat",
            // Queue
            "queue_add",
            "queue_play_next",
            "queue_move",
            "queue_remove",
            "queue_jump",
            "queue_clear",
            // Library
            "toggle_like",
            "create_playlist",
            "import_yt_playlist",
            "export_playlist",
            "import_playlist",
            "delete_playlist",
            "rename_playlist",
            "move_playlist",
            "add_to_playlist",
            "remove_from_playlist",
            "bootstrap",
            // Offline downloads
            "download_tracks",
            "remove_downloads",
            // yt-dlp setup
            "check_ytdlp",
            "set_yt_dlp_path",
            "download_ytdlp",
            // Updates
            "check_update",
            "set_update_notifications",
            "open_url",
            // Window controls
            "window_minimize",
            "window_toggle_maximize",
            "window_close",
        ]),
    ))
    .expect("failed to run tauri-build");
}
